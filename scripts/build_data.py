"""Bundle plant inventory and heat evidence for the Nimbus dashboard."""

import argparse
import csv
import json
from collections import defaultdict
from pathlib import Path
from statistics import median


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "src/features/assessment/plant-records.ts"


def records(filename):
    with (ROOT / "public" / "docs" / filename).open(encoding="utf-8-sig", newline="") as source:
        return list(csv.DictReader(source))


def heat_evidence():
    by_plant = defaultdict(list)
    for row in records("research/nimbus-hot-days-model-counts.csv"):
        by_plant[row["plant_id"]].append(row)

    expected_models = {row["model"] for rows in by_plant.values() for row in rows}
    result = {}
    for plant_id, rows in by_plant.items():
        models = {row["model"] for row in rows}
        grids = {(float(row["grid_latitude"]), float(row["grid_longitude"])) for row in rows}
        if len(rows) != 7 or models != expected_models or len(models) != len(rows) or len(grids) != 1:
            raise SystemExit(f"{plant_id} must have seven matching climate models and one grid centre.")
        counts = [{"model": row["model"], "baseline": int(row["hot_days_2026"]),
                   "future": int(row["hot_days_2040"])} for row in rows]
        if any(not 0 <= row["baseline"] <= 365 or not 0 <= row["future"] <= 366 for row in counts):
            raise SystemExit(f"{plant_id} has an invalid annual hot-day count.")
        latitude, longitude = grids.pop()
        result[plant_id] = {
            "baseline": median(row["baseline"] for row in counts),
            "future": median(row["future"] for row in counts),
            "latitude": latitude,
            "longitude": longitude,
            "modelCounts": counts,
        }
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    inventory = records("nimbus_cement_plants.csv")
    heat = heat_evidence()
    if len(inventory) != 9 or {plant["plant_id"] for plant in inventory} != heat.keys():
        raise SystemExit("The portfolio must have nine matching inventory and heat records.")

    portfolio = []
    for plant in inventory:
        plant_id = plant["plant_id"]
        portfolio.append({
            "id": plant_id,
            "name": plant["town"],
            "state": plant["state"],
            "type": plant["plant_type"],
            "employees": int(plant["employees"]),
            "cement": float(plant["cement_output_fy2025_26_mt"]),
            "clinker": float(plant["clinker_produced_fy2025_26_mt"]),
            "emissions": int(plant["scope1_co2_fy2025_26_kt"]),
            "revenue": int(plant["revenue_fy2025_26_inr_cr"]),
            "notes": plant["notes"],
            "heat": heat[plant_id],
        })

    data = "// Generated by build_data.py from the plant inventory and NASA model counts.\n"
    data += "export const plantRecords = [\n"
    data += ",\n".join("  " + json.dumps(plant, ensure_ascii=False) for plant in portfolio)
    data += "\n];\n"
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != data:
            raise SystemExit("plant-records.ts is out of date. Run build_data.py to regenerate it.")
    else:
        OUTPUT.write_text(data, encoding="utf-8")


if __name__ == "__main__":
    main()
